CREATE SCHEMA "payments";

CREATE SCHEMA "frauds";

CREATE TYPE "payments"."payment_status" AS ENUM (
  'successful',
  'failed',
  'refunded',
  'reversed'
);

CREATE TYPE "payments"."review_status" AS ENUM (
  'init',
  'cleared',
  'pending',
  'reviewed'
);

CREATE TABLE "payments"."states" (
  "state_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "state" varchar(60) UNIQUE NOT NULL
);

CREATE TABLE "payments"."cities" (
  "city_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "city" varchar(80) NOT NULL,
  "zip" varchar(10) NOT NULL,
  "city_pop" int,
  "state_id" int NOT NULL
);

CREATE TABLE "payments"."addresses" (
  "address_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "street" varchar(120) NOT NULL,
  "lat" numeric(9,6) NOT NULL,
  "long" numeric(9,6) NOT NULL,
  "city_id" int NOT NULL
);

CREATE TABLE "payments"."jobs" (
  "job_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "job" varchar(60) UNIQUE NOT NULL
);

CREATE TABLE "payments"."customers" (
  "customer_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "first_name" varchar(40) NOT NULL,
  "last_name" varchar(80) NOT NULL,
  "gender" char(1) NOT NULL,
  "dob" date NOT NULL,
  "job_id" int NOT NULL,
  "address_id" bigint NOT NULL
);

CREATE TABLE "payments"."activities" (
  "activity_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "category" varchar(60) UNIQUE NOT NULL
);

CREATE TABLE "payments"."merchants" (
  "merchant_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "merchant" varchar(80) UNIQUE NOT NULL
);

CREATE TABLE "payments"."currencies" (
  "currency_id" char(3) PRIMARY KEY,
  "currency" varchar(60)
);

CREATE TABLE "payments"."analysts" (
  "analyst_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "role" varchar(60)
);

CREATE TABLE "payments"."transactions" (
  "transaction_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "trans_num" varchar(32) UNIQUE NOT NULL,
  "transdate_transtime" timestamptz NOT NULL,
  "cc_num" varchar(20) NOT NULL,
  "ip_geoloc" varchar(45),
  "device_type" varchar(20),
  "amount_presentation" numeric(20,4) NOT NULL,
  "amt" numeric(20,4) NOT NULL,
  "currency_rate" numeric(20,10) NOT NULL,
  "currency_id_presentation" char(3) NOT NULL,
  "currency_id_received" char(3) NOT NULL,
  "fraud_score" numeric(6,4),
  "model_version" varchar(40),
  "status" payments.payment_status NOT NULL,
  "review_status" payments.review_status NOT NULL,
  "refunded_at" timestamptz,
  "analyst_id" int,
  "is_fraud" boolean,
  "verdict_at" timestamptz,
  "merch_lat" numeric(9,6) NOT NULL,
  "merch_long" numeric(9,6) NOT NULL,
  "customer_id" bigint NOT NULL,
  "merchant_id" bigint NOT NULL,
  "activity_id" int NOT NULL,
  CONSTRAINT "ck_tx_verdict_needs_analyst" CHECK (verdict_at IS NULL OR analyst_id IS NOT NULL),
  CONSTRAINT "ck_tx_analyst_needs_verdict" CHECK (analyst_id IS NULL OR is_fraud IS NOT NULL),
  CONSTRAINT "ck_tx_init" CHECK (review_status <> 'init' OR (coalesce(analyst_id, -1) = 0 AND is_fraud IS NOT NULL AND verdict_at IS NOT NULL)),
  CONSTRAINT "ck_tx_reviewed_needs_analyst" CHECK (review_status <> 'reviewed' OR analyst_id IS NOT NULL),
  CONSTRAINT "ck_tx_scored_unless_init" CHECK (review_status = 'init' OR (fraud_score IS NOT NULL AND model_version IS NOT NULL)),
  CONSTRAINT "ck_tx_reviewed_needs_verdict" CHECK (review_status <> 'reviewed' OR verdict_at IS NOT NULL),
  CONSTRAINT "ck_tx_refund_status" CHECK (refunded_at IS NULL OR status IN ('refunded', 'reversed'))
);

CREATE TABLE "frauds"."rejects" (
  "reject_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "trans_num" varchar(32) UNIQUE NOT NULL,
  "customer_id" bigint NOT NULL,
  "first_name" varchar(40) NOT NULL,
  "last_name" varchar(80) NOT NULL,
  "dob" date NOT NULL,
  "merchant_id" bigint NOT NULL,
  "merchant" varchar(80) NOT NULL,
  "activity_id" int NOT NULL,
  "transdate_transtime" timestamptz NOT NULL,
  "cc_num" varchar(20) NOT NULL,
  "ip_geoloc" varchar(45),
  "device_type" varchar(20),
  "amount_presentation" numeric(20,4) NOT NULL,
  "currency_id_presentation" char(3) NOT NULL,
  "amt" numeric(20,4) NOT NULL,
  "merch_lat" numeric(9,6) NOT NULL,
  "merch_long" numeric(9,6) NOT NULL,
  "fraud_score" numeric(6,4) NOT NULL,
  "model_version" varchar(40) NOT NULL
);

CREATE INDEX "ix_city_state" ON "payments"."cities" ("state_id");

CREATE UNIQUE INDEX "uq_city_key" ON "payments"."cities" ("city", "state_id", "zip");


CREATE INDEX "ix_addr_city" ON "payments"."addresses" ("city_id");

CREATE UNIQUE INDEX "uq_addr_key" ON "payments"."addresses" ("street", "lat", "long", "city_id");


CREATE INDEX "ix_cust_address" ON "payments"."customers" ("address_id");

CREATE INDEX "ix_cust_job" ON "payments"."customers" ("job_id");

CREATE UNIQUE INDEX "uq_cust_key" ON "payments"."customers" ("first_name", "last_name", "dob");


CREATE INDEX "ix_tx_customer" ON "payments"."transactions" ("customer_id");

CREATE INDEX "ix_tx_merchant" ON "payments"."transactions" ("merchant_id");

CREATE INDEX "ix_tx_analyst" ON "payments"."transactions" ("analyst_id");

CREATE INDEX "ix_tx_ccy_presentation" ON "payments"."transactions" ("currency_id_presentation");

CREATE INDEX "ix_tx_ccy_received" ON "payments"."transactions" ("currency_id_received");

CREATE INDEX "ix_tx_datetime" ON "payments"."transactions" ("transdate_transtime");

CREATE INDEX "ix_tx_activity" ON "payments"."transactions" ("activity_id");

CREATE INDEX ix_tx_pending ON "payments"."transactions" (transaction_id) WHERE review_status = 'pending';

CREATE INDEX ix_tx_is_fraud ON "payments"."transactions" (transaction_id) WHERE is_fraud;



CREATE INDEX "ix_rej_datetime" ON "frauds"."rejects" ("transdate_transtime");

CREATE INDEX "ix_rej_customer" ON "frauds"."rejects" ("customer_id");

CREATE INDEX "ix_rej_merchant" ON "frauds"."rejects" ("merchant_id");



